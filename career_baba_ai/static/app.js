const careerForm = document.querySelector("#career-form");
const resumeForm = document.querySelector("#resume-form");
const results = document.querySelector("#results");
const toast = document.querySelector("#toast");

function showToast(message) {
  toast.textContent = message;
  toast.hidden = false;
  setTimeout(() => {
    toast.hidden = true;
  }, 5000);
}

function formToObject(form) {
  const data = new FormData(form);
  return Object.fromEntries(data.entries());
}

function list(items = [], warning = false) {
  if (!items.length) return "<p class='muted'>No items returned yet.</p>";
  return `<div class="pill-row">${items
    .map((item) => `<span class="pill ${warning ? "warn" : ""}">${item}</span>`)
    .join("")}</div>`;
}

function scoreBar(score = 0) {
  return `<div class="score-bar"><span style="width:${Math.min(score || 0, 100)}%"></span></div>`;
}

async function readApiResponse(response) {
  const payload = await response.json();
  if (response.status === 401) {
    window.location.href = "/login";
    return null;
  }

  if (!response.ok) {
    throw new Error(payload.error || "Request failed");
  }

  return payload;
}

function renderReport(data, aiUsed, notice) {
  const topRoles = data.top_roles || [];
  const skillGap = data.skill_gap || {};
  const skillMatch = data.skill_match || {};
  const marketDemand = data.market_demand || [];
  const careerOptions = data.top_career_options?.length ? data.top_career_options : topRoles;
  const readiness = skillGap.readiness_score || 0;

  results.innerHTML = `
    <div class="panel">
      <div class="section-head">
        <p class="eyebrow">${aiUsed ? "Generated by Gemini" : "Fallback report"}</p>
        <h2>AI Career Intelligence Report</h2>
      </div>
      ${notice ? `<p class="toast-inline">${notice}</p>` : ""}
      <p>${data.profile_summary || ""}</p>
    </div>

    <div class="report-grid" style="margin-top: 18px;">
      <section class="report-card">
        <h3>Market Demand</h3>
        <div class="feature-list">
          ${
            marketDemand
              .map(
                (item) => `
                  <div>
                    <strong>${item.role} &middot; ${item.demand_score}% demand</strong>
                    ${scoreBar(item.demand_score)}
                    <p>${item.trend || ""}</p>
                  </div>
                `
              )
              .join("") || "<p class='muted'>No market demand returned yet.</p>"
          }
        </div>
      </section>

      <section class="report-card">
        <h3>Detected Skills</h3>
        ${list(data.detected_skills || [])}
      </section>
    </div>

    <div class="report-grid" style="margin-top: 18px;">
      <section class="report-card">
        <h3>Top Career Options</h3>
        <div class="feature-list">
          ${
            careerOptions
              .map(
                (role) => `
                  <div class="role-card">
                    <strong>${role.title} &middot; ${role.fit_score}% fit</strong>
                    ${scoreBar(role.fit_score)}
                    ${role.why ? `<p>${role.why}</p>` : ""}
                    ${role.growth_signal ? `<p class="muted">${role.growth_signal}</p>` : ""}
                  </div>
                `
              )
              .join("") || "<p class='muted'>No role matches returned yet.</p>"
          }
        </div>
      </section>

      <section class="report-card">
        <h3>AI Career Prediction</h3>
        <p><strong>${data.selected_role || topRoles[0]?.title || "Role not selected yet"}</strong></p>
        <h4>Why this role?</h4>
        ${list(data.why_this_role || [])}
        <h4>Required skills</h4>
        ${list(data.required_skills || [])}
        <h4>Target companies</h4>
        ${list(data.target_companies || [])}
      </section>
    </div>

    <div class="report-grid" style="margin-top: 18px;">
      <section class="report-card">
        <h3>Skill Gap Visualization</h3>
        <p><strong>${readiness}% readiness</strong></p>
        ${scoreBar(readiness)}
        <div class="split-list">
          <div>
            <h4>Skills You Have</h4>
            ${list(skillMatch.matched || skillGap.strong_skills || [])}
          </div>
          <div>
            <h4>Skills Missing</h4>
            ${list(skillMatch.missing || skillGap.missing_skills || [], true)}
          </div>
        </div>
      </section>

      <section class="report-card">
        <h3>Career Readiness</h3>
        <p>${readiness >= 70 ? "You are close to job-ready for this direction." : "You need focused improvement before applying widely."}</p>
        <h3>Skills You Should Learn</h3>
        ${list(data.recommended_skills || skillGap.missing_skills || [], true)}
      </section>
    </div>

    <div class="report-grid" style="margin-top: 18px;">
      <section class="report-card">
        <h3>Recommended Projects</h3>
        <div class="feature-list">
          ${
            (data.projects || [])
              .map(
                (project) => `
                  <div>
                    <strong>${project.title} &middot; ${project.level}</strong>
                    <p>${project.description}</p>
                    ${list(project.success_metrics || [])}
                  </div>
                `
              )
              .join("") || "<p class='muted'>No projects returned yet.</p>"
          }
        </div>
      </section>

      <section class="report-card">
        <h3>Career Roadmap</h3>
        <div class="feature-list">
          ${
            (data.learning_plan || [])
              .map(
                (item) => `
                  <div>
                    <strong>${item.phase} &middot; ${item.duration}</strong>
                    <p>${item.actions}</p>
                  </div>
                `
              )
              .join("") || "<p class='muted'>No roadmap returned yet.</p>"
          }
        </div>
      </section>
    </div>

    <div class="report-grid" style="margin-top: 18px;">
      <section class="report-card">
        <h3>Resume Feedback</h3>
        ${list(data.resume_feedback || [], true)}
      </section>

      <section class="report-card">
        <h3>Market Insights</h3>
        ${list(data.market_insights || [])}
        <h3>Next Actions</h3>
        ${list(data.next_actions || [])}
        ${
          data.sources?.length
            ? `<h3>Sources</h3><div class="feature-list">${data.sources
                .map((source) => `<a href="${source.url}" target="_blank" rel="noreferrer">${source.title}</a>`)
                .join("")}</div>`
            : ""
        }
      </section>
    </div>
  `;

  results.scrollIntoView({ behavior: "smooth", block: "start" });
}

async function analyzeProfile(event) {
  event.preventDefault();
  const button = careerForm.querySelector("button");
  button.disabled = true;
  button.textContent = "Generating AI report...";

  try {
    const response = await fetch("/api/analyze", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(formToObject(careerForm)),
    });
    const payload = await readApiResponse(response);
    if (!payload) return;
    renderReport(payload.result, payload.ai_used, payload.notice);
  } catch (error) {
    showToast(`Could not generate report: ${error.message}`);
  } finally {
    button.disabled = false;
    button.textContent = "Generate AI Career Report";
  }
}

async function analyzeResume(event) {
  event.preventDefault();
  const button = resumeForm.querySelector("button");
  const profileData = new FormData(careerForm);
  const resumeData = new FormData(resumeForm);

  for (const [key, value] of profileData.entries()) {
    resumeData.append(key, value);
  }

  button.disabled = true;
  button.textContent = "Analyzing resume...";

  try {
    const response = await fetch("/api/resume", {
      method: "POST",
      body: resumeData,
    });
    const payload = await readApiResponse(response);
    if (!payload) return;
    renderReport(payload.result, payload.ai_used, payload.notice);
  } catch (error) {
    showToast(`Could not analyze resume: ${error.message}`);
  } finally {
    button.disabled = false;
    button.textContent = "Analyze Resume With AI";
  }
}

careerForm.addEventListener("submit", analyzeProfile);
resumeForm.addEventListener("submit", analyzeResume);
